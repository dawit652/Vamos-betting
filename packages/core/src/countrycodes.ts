/** Lower case, accents and punctuation dropped, "&" read as "and", spaces collapsed. */
function normalizeName(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

const CODE_BY_NAME: ReadonlyMap<string, string> = new Map(
  COUNTRY_NAMES.flatMap(([code, ...names]) => names.map((name) => [normalizeName(name), code])),
);

/** Words a board puts after a country for its sub-competitions: "England Amateur", "Poland U21". */
const QUALIFIER = /^(amateurs?|youth|women|womens|men|mens|reserves?|cup|cups|clubs?|u\d{2})$/;

/**
 * The flag code of a country name as bookmakers write it, or null when it is not one. A country
 * followed by qualifiers (Amateur, Youth, Women, Reserves, U21, Cup, Clubs) takes the country's
 * flag; "International" and "World" have no flag code.
 */
export function countryCodeOfName(name: string): string | null {
  const words = normalizeName(name).split(' ');
  while (words.length > 0) {
    const code = CODE_BY_NAME.get(words.join(' '));
    if (code !== undefined) return code;
    const last = words[words.length - 1] ?? '';
    if (words.length === 1 || !QUALIFIER.test(last)) return null;
    words.pop();
  }
  return null;
}
